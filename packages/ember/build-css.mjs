// Builds @ember-joinery/ember's CSS into dist/ (see "Styling pipeline" in JOINERY_PLAN.md).
// The rollup build runs it after writing the JavaScript; `node build-css.mjs` runs it alone.
//
// What ships:
//
//   dist/joinery.css            the components in the Nova style, shadcn's default
//   dist/styles/<style>.css     the same in each of the other seven styles (Luma, Lyra, …)
//   dist/tokens.css             the default theme: the Neutral base colour, light and `.dark`
//   dist/themes/<colour>.css    each of shadcn's base colours, to use instead of tokens.css
//   dist/tailwind.css           for Tailwind apps: the tokens mapped to Tailwind's theme
//
// A style's CSS is one Tailwind v4 compile of, in this order: src/css/setup.css (Tailwind's
// theme, inlined, tw-animate-css, shadcn's variants and the token mapping; it emits nothing of
// its own), then, in `@layer joinery`, src/css/base.css, the ported sheet
// (src/styles/<style>.css), and every component's own rules (src/components/**/*.css, A–Z:
// the inline utilities scripts/extract-classes.mjs pulls out of upstream's source). The entry
// is generated here, so adding a component's CSS file is all it takes to ship it. The themes
// and tailwind.css are copied as written.
//
// Everything a style ships is in `@layer joinery`, but for what Tailwind puts at the top level
// for the rules to use (`@property` registrations, keyframes, and `@layer properties`, its
// fallback for browsers without `@property`). An unlayered rule would beat an app's own layered
// CSS, so `layered()` checks each compile and fails the build on one (see there for the one it
// drops).

import { spawnSync } from 'node:child_process'
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} from 'node:fs'
import { basename, dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const packageDir = dirname(fileURLToPath(import.meta.url))

/** The style shipped as dist/joinery.css; the others go to dist/styles/<style>.css. */
export const DEFAULT_STYLE = 'nova'

/** The base colour shipped as dist/tokens.css. */
export const DEFAULT_BASE_COLOR = 'neutral'

const tailwind = join(packageDir, 'node_modules', '.bin', 'tailwindcss')

/** The `.css` files in a folder under the package, A–Z, as paths from the package (or none). */
function cssFiles(folder, { recursive = false } = {}) {
  const dir = join(packageDir, folder)
  if (!existsSync(dir)) return []
  return readdirSync(dir, { recursive })
    .map(String)
    .filter(name => name.endsWith('.css'))
    .map(name => join(folder, name).split('\\').join('/'))
    .sort()
}

/** The ported styles, by name. */
export function styles() {
  return cssFiles('src/styles').map(file => basename(file, '.css'))
}

/** Every component's own CSS, A–Z by path. */
export function componentCss() {
  return cssFiles('src/components', { recursive: true })
}

/** The entry Tailwind compiles for a style, importing everything by absolute path. */
export function styleEntry(style) {
  const at = file => JSON.stringify(join(packageDir, file))
  return [
    `/* Generated by build-css.mjs: the ${style} style. */`,
    `@import ${at('src/css/setup.css')};`,
    `@import ${at('src/css/base.css')} layer(joinery);`,
    `@import ${at(`src/styles/${style}.css`)} layer(joinery);`,
    ...componentCss().map(file => `@import ${at(file)} layer(joinery);`),
    '',
  ].join('\n')
}

/**
 * Every file the build writes, as `{ output, entry?, input? }` with the output's path from
 * dist/: an `entry` is compiled, an `input` copied as written.
 */
export function entries() {
  return [
    ...styles().map(style => ({
      output: style === DEFAULT_STYLE ? 'joinery.css' : `styles/${style}.css`,
      entry: styleEntry(style),
      style,
    })),
    { output: 'tokens.css', input: `src/themes/${DEFAULT_BASE_COLOR}.css` },
    ...cssFiles('src/themes').map(file => ({ output: `themes/${basename(file)}`, input: file })),
    { output: 'tailwind.css', input: 'src/tailwind.css' },
  ]
}

/**
 * CSS's top-level statements and blocks (`@layer x;`, `a { … }`, `@media … { … }`), as
 * `{ text, start, end }` offsets into it, skipping comments and leaving braces in strings alone.
 */
export function topLevel(css) {
  const blocks = []
  let depth = 0
  let start = 0
  let quote
  const push = end => {
    const text = css.slice(start, end).trim()
    if (text) blocks.push({ text, start, end })
    start = end
  }
  for (let index = 0; index < css.length; index++) {
    const char = css[index]
    if (quote) {
      if (char === '\\') index++
      else if (char === quote) quote = undefined
      continue
    }
    if (char === '/' && css[index + 1] === '*') {
      const end = css.indexOf('*/', index + 2)
      index = end === -1 ? css.length : end + 1
      if (depth === 0) start = index + 1
      continue
    }
    if (char === '"' || char === "'") quote = char
    else if (char === '{') depth++
    else if (char === '}' && --depth === 0) push(index + 1)
    else if (char === ';' && depth === 0) push(index + 1)
  }
  return blocks
}

/** What may sit outside `@layer joinery`: what Tailwind emits for the rules to use. */
const TOP_LEVEL = /^@(layer|property|keyframes|-webkit-keyframes|charset)\b/

/**
 * shadcn.css's last rule, kept upstream for backwards compatibility: unlayered, so it wins over
 * other utilities on an element with a bare `.shimmer` class. Joinery's parts never have one (a
 * part's rule `@apply`s `shimmer`, which brings the utility's own reduced-motion rule along), so
 * all it would do is reach into an app's own `.shimmer` elements.
 */
const SHIMMER_COMPAT =
  /^@media\s*\(prefers-reduced-motion:\s*reduce\)\s*\{\s*\.shimmer\s*\{[^{}]*\}\s*\}$/

/**
 * A compiled style, checked: everything but what Tailwind emits for the rules to use is in a
 * layer. It drops shadcn.css's unlayered `.shimmer` rule (see SHIMMER_COMPAT) and throws on any
 * other unlayered CSS.
 */
export function layered(css, style = 'a') {
  let output = ''
  let from = 0
  for (const block of topLevel(css)) {
    if (TOP_LEVEL.test(block.text)) continue
    if (SHIMMER_COMPAT.test(block.text)) {
      output += css.slice(from, block.start)
      from = block.end
      continue
    }
    throw new Error(
      `build-css: the ${style} style has CSS outside @layer joinery, which would beat an app's own layered CSS:\n${block.text.slice(0, 300)}`,
    )
  }
  return output + css.slice(from)
}

/** Compiles one style's entry with the Tailwind CLI into `output`, or throws with its output. */
function compile(entry, output, style) {
  if (!existsSync(tailwind)) {
    throw new Error(`build-css: ${tailwind} is missing; run pnpm install`)
  }
  const cache = join(packageDir, 'node_modules', '.cache', 'joinery-css')
  mkdirSync(cache, { recursive: true })
  const input = join(cache, `${style}.css`)
  writeFileSync(input, entry)
  const result = spawnSync(tailwind, ['--input', input, '--output', output], {
    cwd: packageDir,
    encoding: 'utf8',
  })
  if (result.status !== 0) {
    throw new Error(`build-css: tailwindcss failed on the ${style} style\n${result.stderr}`)
  }
  writeFileSync(output, layered(readFileSync(output, 'utf8'), style))
}

/** Builds every file into `outDir`. */
export function buildCss({ outDir = join(packageDir, 'dist') } = {}) {
  for (const item of entries()) {
    const output = resolve(outDir, item.output)
    mkdirSync(dirname(output), { recursive: true })
    if (item.entry) compile(item.entry, output, item.style)
    else copyFileSync(resolve(packageDir, item.input), output)
  }
}

/** What a CSS rebuild depends on: every style sheet under src/. */
export function watchedFiles() {
  return cssFiles('src', { recursive: true }).map(file => join(packageDir, file))
}

/** The rollup plugin: rebuilds the CSS after every (re)build, and watches its sources. */
export function joineryCss() {
  return {
    name: 'joinery-css',
    buildStart() {
      for (const file of watchedFiles()) this.addWatchFile(file)
    },
    writeBundle(options) {
      buildCss({ outDir: options.dir ? resolve(options.dir) : undefined })
    },
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    buildCss()
    const dist = relative(process.cwd(), join(packageDir, 'dist')) || '.'
    console.log(`build-css: wrote ${entries().length} files into ${dist}/`)
  } catch (error) {
    console.error(error.message)
    process.exitCode = 1
  }
}
