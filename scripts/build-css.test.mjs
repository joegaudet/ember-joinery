import { test } from 'node:test'
import assert from 'node:assert/strict'
import { existsSync, readFileSync, readdirSync } from 'node:fs'
import { join } from 'node:path'
import {
  MERGED,
  layered,
  mergedRules,
  sheetRule,
  styleEntry,
  styleVariants,
  styles,
  topLevel,
} from '../packages/ember/build-css.mjs'
import { repoRoot } from './upstream.mjs'

const dist = join(repoRoot, 'packages/ember/dist')

test('topLevel splits CSS into its statements and blocks, past comments and strings', () => {
  const css = `/*! a banner { } */
@layer properties;
@property --x { syntax: "*"; inherits: false; }
a { content: "}"; }
@layer joinery { :where(.b) { color: red; } }`
  assert.deepEqual(
    topLevel(css).map(block => block.text),
    [
      '@layer properties;',
      '@property --x { syntax: "*"; inherits: false; }',
      'a { content: "}"; }',
      '@layer joinery { :where(.b) { color: red; } }',
    ],
  )
})

test("layered keeps what Tailwind emits for the rules, and drops shadcn's unlayered .shimmer rule", () => {
  const css = `/*! tailwindcss */
@layer properties;
@property --shimmer-angle {
  syntax: "<angle>";
  inherits: true;
  initial-value: 20deg;
}
@media (prefers-reduced-motion: reduce) {
  .shimmer {
    animation: none;
    background-image: none;
    -webkit-text-fill-color: currentColor;
  }
}
@layer joinery {
  :where(.jn-x) { color: red; }
}
@keyframes spin { to { transform: rotate(360deg); } }
@layer properties { @supports (x: y) { :root, :host { --shimmer-angle: 20deg; } } }
`
  const out = layered(css, 'nova')
  assert.doesNotMatch(out, /\.shimmer/)
  assert.match(out, /@property --shimmer-angle/)
  assert.match(out, /@layer joinery \{\n {2}:where\(\.jn-x\)/)
  assert.match(out, /@keyframes spin/)
  assert.match(out, /@layer properties \{ @supports/)
})

test('layered fails on any other CSS outside a layer', () => {
  assert.throws(
    () => layered('@layer joinery { :where(.a) { color: red; } }\n.b { color: blue; }\n', 'lyra'),
    /the lyra style has CSS outside @layer joinery[^]*\.b \{ color: blue; \}/,
  )
  assert.throws(
    () => layered('@media (hover: hover) { .c { color: red; } }'),
    /outside @layer joinery/,
  )
})

test(
  'every compiled style is layered',
  { skip: !existsSync(join(dist, 'joinery.css')) && 'build the packages first' },
  () => {
    const files = [
      join(dist, 'joinery.css'),
      ...readdirSync(join(dist, 'styles')).map(name => join(dist, 'styles', name)),
    ]
    assert.strictEqual(files.length, 8)
    for (const file of files) {
      const css = readFileSync(file, 'utf8')
      assert.strictEqual(layered(css, file), css, `${file} has nothing unlayered`)
      assert.doesNotMatch(css, /^\s*\.shimmer\b/m, file)
    }
  },
)

test("sheetRule reads the utilities a sheet's own rule for a class applies", () => {
  const sheet = [
    ':where(.jn-a) {',
    '  @apply px-2 hover:bg-muted;',
    '}',
    ':where(.jn-a-icon) {',
    '  @apply size-3;',
    '}',
    ':where(.jn-b) :where(.jn-a) {',
    '  @apply p-1;',
    '}',
  ].join('\n')
  assert.strictEqual(sheetRule(sheet, 'jn-a'), 'px-2 hover:bg-muted')
  assert.strictEqual(sheetRule(sheet, 'jn-a-icon'), 'size-3')
  assert.strictEqual(sheetRule(sheet, 'jn-c'), undefined)
})

test("mergedRules repeats the winning class's rule for an element with both classes", () => {
  const sheet = ':where(.jn-t) {\n  @apply px-2.5 py-1.5;\n}\n:where(.jn-l) {\n  @apply p-2;\n}\n'
  const css = mergedRules(sheet, [
    { on: 'jn-l', wins: 'jn-t' },
    { on: 'jn-l', wins: 'jn-missing' },
  ])
  assert.match(css, /^\/\* Generated by build-css\.mjs/)
  assert.match(css, /\n:where\(\.jn-l\.jn-t\) \{\n {2}@apply px-2\.5 py-1\.5;\n\}\n/)
  assert.doesNotMatch(css, /jn-missing/, 'nothing for a class the sheet has no rule for')
})

test('every style has a rule for each MERGED winner, and its entry puts them after its sheet', () => {
  for (const style of styles()) {
    const sheet = readFileSync(join(repoRoot, `packages/ember/src/styles/${style}.css`), 'utf8')
    for (const { wins } of MERGED) assert.ok(sheetRule(sheet, wins), `${style}: .${wins}`)
    const entry = styleEntry(style)
    const at = name => entry.indexOf(name)
    assert.ok(
      at(`src/styles/${style}.css`) < at(`${style}-merged.css`),
      `${style}: after the sheet`,
    )
    assert.ok(at(`${style}-merged.css`) < at('src/components/'), `${style}: before the components`)
  }
})

test(
  "a link with the trigger's look takes the trigger's padding, as upstream's tailwind-merge gives it",
  { skip: !existsSync(join(dist, 'joinery.css')) && 'build the packages first' },
  () => {
    const css = readFileSync(join(dist, 'joinery.css'), 'utf8')
    const at = selector => css.indexOf(selector)
    const merged = ':where(.jn-navigation-menu-link.jn-navigation-menu-trigger)'
    assert.ok(at(merged) > at(':where(.jn-navigation-menu-link)'), 'after the link rule')
    const rule = css.slice(at(merged), css.indexOf('}', at(merged)))
    assert.match(rule, /padding-inline: calc\((?:var\(--spacing\)|0\.25rem) \* 2\.5\);/, 'px-2.5')
    assert.match(rule, /padding-block: calc\((?:var\(--spacing\)|0\.25rem) \* 1\.5\);/, 'py-1.5')
  },
)

test('each style declares a variant for every style, which matches only in its own', () => {
  assert.strictEqual(styles().length, 8)
  for (const style of styles()) {
    const variants = styleVariants(style)
    assert.strictEqual(variants.length, 8)
    for (const other of styles()) {
      const selector = other === style ? '&' : '&:not(*)'
      assert.ok(
        variants.includes(`@custom-variant style-${other} (${selector});`),
        `${style} declares style-${other} as ${selector}`,
      )
    }
    const entry = styleEntry(style)
    const lastImport = entry.lastIndexOf('@import ')
    assert.ok(
      entry.indexOf('@custom-variant') > lastImport,
      'after every @import, which CSS ignores once another rule comes first',
    )
  }
})

test("trace.css restates each sheet's utilities for a line's wrapper, through an overlay's root", () => {
  const read = file => readFileSync(join(repoRoot, 'packages/ember/src', file), 'utf8')
  const trace = read('components/trace.css')
  const wrapper = '*:has-[>[data-slot=trace-line]]:'
  for (const style of styles()) {
    const sheet = read(`styles/${style}.css`)
    const rule = /^:where\(\.jn-trace\) \{\s*@apply ([^;]+);/m.exec(sheet)
    assert.ok(rule, `the ${style} sheet has a rule for the trace`)
    const expected = rule[1]
      .split(/\s+/)
      .filter(utility => utility.startsWith(wrapper))
      .map(utility => utility.slice(wrapper.length))
    assert.ok(expected.length > 0, `the ${style} sheet styles what wraps a line`)
    const copy = new RegExp(`@variant style-${style} \\{\\s*@apply ([^;]+);`).exec(trace)
    assert.ok(copy, `trace.css has a style-${style} block`)
    assert.deepStrictEqual(copy[1].split(/\s+/), expected, `trace.css matches the ${style} sheet`)
  }
})

test("questionnaire.css restates each sheet's responsive height for the action row, after the inline rule", () => {
  const read = file => readFileSync(join(repoRoot, 'packages/ember/src', file), 'utf8')
  const questionnaire = read('components/questionnaire.css')
  const inline = questionnaire.indexOf('@apply grid min-h-11 w-full')
  assert.ok(inline > 0, 'questionnaire.css has the inline rule for the action row')
  const blocks = questionnaire.slice(inline)
  for (const style of styles()) {
    const sheet = read(`styles/${style}.css`)
    const rule = /^:where\(\.jn-questionnaire-actions\) \{\s*@apply ([^;]+);/m.exec(sheet)
    assert.ok(rule, `the ${style} sheet has a rule for the action row`)
    const expected = rule[1].split(/\s+/).filter(utility => /^[a-z0-9-]+:min-h-/.test(utility))
    assert.ok(expected.length > 0, `the ${style} sheet gives the action row a responsive height`)
    const copy = new RegExp(`@variant style-${style} \\{\\s*@apply ([^;]+);`).exec(blocks)
    assert.ok(copy, `questionnaire.css has a style-${style} block after the inline rule`)
    assert.deepStrictEqual(
      copy[1].split(/\s+/),
      expected,
      `questionnaire.css matches the ${style} sheet`,
    )
  }
})
