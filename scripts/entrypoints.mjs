// The public entrypoints of the packages built with rollup (primitives, ember and the add-ons),
// in place of @embroider/addon-dev's publicEntrypoints(). Each of those package.json files maps
// `./*` to `./dist/*.js` (types: `./declarations/*.d.ts`), so every entrypoint is a subpath:
//
//   src/index.ts                     dist/index.js              the barrel
//   src/visually-hidden.gts          dist/visually-hidden.js    <pkg>/visually-hidden
//   src/anchor/index.ts              dist/anchor.js             <pkg>/anchor
//   src/components/dialog/index.gts  dist/components/dialog.js  <pkg>/components/dialog
//   src/test-support/index.ts        dist/test-support.js       <pkg>/test-support
//   src/template-registry.ts         dist/template-registry.js  <pkg>/template-registry
//
// The modules are the ones the barrels export, found by the same walk (scripts/gen-barrels.mjs),
// plus the barrels themselves and `template-registry`. Files inside a folder feature, `-private`
// folders and `_` names are private: rollup bundles them into the entrypoints that use them.
//
// ember-tsc writes a folder feature's types to declarations/anchor/index.d.ts, so once it has
// finished, the plugin writes declarations/anchor.d.ts to re-export them.

import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve, sep } from 'node:path'
import { INDEX_FILES, stripExtension, walkModules } from './gen-barrels.mjs'

const TYPES_HEADER =
  '// Generated by scripts/entrypoints.mjs: the types of a folder feature, for its subpath.'

/** `anchor/index.ts` → `anchor.js`; `components/button.gts` → `components/button.js`. */
export function entryFileName(source) {
  const parts = source.split('/')
  const file = parts.pop()
  if (parts.length > 0 && INDEX_FILES.includes(file)) return `${parts.join('/')}.js`
  return [...parts, `${stripExtension(file)}.js`].join('/')
}

/** `anchor/index.ts` is a folder feature; `index.ts` (the barrel) and `anchor.ts` are not. */
export function isFolderFeature(source) {
  const parts = source.split('/')
  return parts.length > 1 && INDEX_FILES.includes(parts[parts.length - 1])
}

/**
 * The package's entrypoints, `{ source, fileName }` with `source` relative to `srcDir` and
 * `fileName` relative to dist/. Two modules that would build to one file are an error.
 */
export function publicModules(srcDir) {
  const sources = new Map()
  for (const path of walkModules(srcDir)) {
    const source = relative(srcDir, path).split(sep).join('/')
    const fileName = entryFileName(source)
    const other = sources.get(fileName)
    if (other) {
      throw new Error(
        `${join(srcDir, other)} and ${join(srcDir, source)} are both the subpath ` +
          `${fileName.replace(/\.js$/, '')}. Keep one: a file, or a folder with an index.`,
      )
    }
    sources.set(fileName, source)
  }
  return [...sources].map(([fileName, source]) => ({ source, fileName }))
}

/** Whether a declaration file has a default export (a value or a type). */
export function declaresDefault(declarations) {
  if (/^\s*export\s+default\b/m.test(declarations)) return true
  for (const match of declarations.matchAll(/\bexport\s+(?:type\s+)?\{([^}]*)\}/g)) {
    for (const spec of match[1].split(',')) {
      const parts = spec.trim().split(/\s+as\s+/)
      if (parts[parts.length - 1].trim() === 'default') return true
    }
  }
  return false
}

/** The declarations for a folder feature's subpath, given its index's declarations. */
export function folderTypes(source, indexDeclarations) {
  const parts = source.split('/')
  const specifier = `./${parts[parts.length - 2]}/index.js`
  const lines = [TYPES_HEADER, `export * from '${specifier}'`]
  if (declaresDefault(indexDeclarations)) lines.push(`export { default } from '${specifier}'`)
  return `${lines.join('\n')}\n`
}

/** Writes each folder feature's subpath declarations; returns the files whose contents changed. */
export function writeFolderTypes(srcDir, declarationsDir) {
  const written = []
  for (const { source, fileName } of publicModules(srcDir)) {
    if (!isFolderFeature(source)) continue
    const index = join(declarationsDir, dirname(source), 'index.d.ts')
    // Missing when ember-tsc failed; its own error says why.
    if (!existsSync(index)) continue
    const file = join(declarationsDir, fileName.replace(/\.js$/, '.d.ts'))
    const text = folderTypes(source, readFileSync(index, 'utf8'))
    if (existsSync(file) && readFileSync(file, 'utf8') === text) continue
    writeFileSync(file, text)
    written.push(file)
  }
  return written
}

/**
 * The rollup plugin. Put it after `addon.declarations()`: its writeBundle is sequential, so
 * rollup runs it once the earlier plugins' writeBundle (ember-tsc) has finished.
 */
export function entrypoints({ srcDir = 'src', declarationsDir = 'declarations' } = {}) {
  return {
    name: 'joinery-entrypoints',
    buildStart() {
      for (const { source, fileName } of publicModules(srcDir)) {
        const id = resolve(srcDir, source)
        this.addWatchFile(id)
        this.emitFile({ type: 'chunk', id, fileName })
      }
    },
    writeBundle: {
      sequential: true,
      handler() {
        writeFolderTypes(srcDir, declarationsDir)
      },
    },
  }
}
