#!/usr/bin/env node
// Writes each package's barrel (src/index.ts) from the modules present, so units working in
// parallel never edit a shared index by hand. The barrels are build output: they are
// gitignored and every package's build and typecheck scripts regenerate them.
//
//   node scripts/gen-barrels.mjs                 every package under packages/
//   node scripts/gen-barrels.mjs packages/ember  just these package directories
//
// A package opts in with the folders that get a barrel, relative to the package:
//
//   "joinery": { "barrels": ["src", "src/test-support"] }
//
// What a barrel holds, for its folder:
//
// - Every .ts, .gts, .js and .gjs module in the folder and below it, sorted by path.
// - A module's named exports, through `export * from`.
// - A module's default export, under the PascalCase of its file name
//   (components/button-group.gts becomes ButtonGroup).
// - A folder with its own index file counts as one module: the barrel exports its index and
//   doesn't look inside. A feature can keep private files that way.
// - Skipped: names starting with `_` or `.`, `-private` folders, `*.d.ts`, `*.test.*`,
//   `template-registry.*`, and any folder that has a barrel of its own.
//
// Two modules exporting the same name is an error, because `export *` would silently drop it.

import { existsSync, readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from 'node:fs'
import { basename, dirname, join, relative, resolve, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

export const BARREL_FILE = 'index.ts'

const MODULE_EXTENSIONS = ['.ts', '.gts', '.js', '.gjs']
const INDEX_FILES = MODULE_EXTENSIONS.map(ext => `index${ext}`)

const HEADER = [
  '// Generated by scripts/gen-barrels.mjs from the modules in this folder. Do not edit it:',
  '// the build rewrites it. See "Generated files" in CONTRIBUTING.md.',
]

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')

function isModuleFile(name) {
  if (name.endsWith('.d.ts')) return false
  if (/\.test\.[^.]+$/.test(name)) return false
  if (/^template-registry\.[^.]+$/.test(name)) return false
  return MODULE_EXTENSIONS.some(ext => name.endsWith(ext))
}

function isSkippedName(name) {
  return name.startsWith('_') || name.startsWith('.') || name === '-private'
}

function stripExtension(name) {
  const ext = MODULE_EXTENSIONS.find(e => name.endsWith(e))
  return ext ? name.slice(0, -ext.length) : name
}

/** `button-group` → `ButtonGroup`. */
export function pascalCase(name) {
  return name
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map(part => part[0].toUpperCase() + part.slice(1))
    .join('')
}

/** The barrel's modules, as paths relative to its folder, sorted. */
export function collectModules(barrelDir, { otherBarrels = [] } = {}) {
  const skipDirs = new Set(otherBarrels.map(dir => resolve(dir)))
  const modules = []

  function walk(dir) {
    const entries = readdirSync(dir).sort()
    for (const name of entries) {
      if (isSkippedName(name)) continue
      const path = join(dir, name)
      if (statSync(path).isDirectory()) {
        if (skipDirs.has(resolve(path))) continue
        const index = INDEX_FILES.find(file => existsSync(join(path, file)))
        if (index) modules.push(join(path, index))
        else walk(path)
      } else if (isModuleFile(name) && !(dir === barrelDir && INDEX_FILES.includes(name))) {
        modules.push(path)
      }
    }
  }

  walk(barrelDir)
  return modules.map(path => relative(barrelDir, path).split(sep).join('/')).sort()
}

const hasDefault = source =>
  /^\s*export\s+default\s+(?!(?:interface|type)\b)/m.test(source) ||
  /export\s*\{[^}]*\bas\s+default\b[^}]*\}/.test(source) ||
  /export\s*\{\s*default\s*[,}]/.test(source)

const hasNamed = source => /^\s*export\s+(?!default\b)/m.test(source)

/** The names a module exports, as far as a regular expression can tell. */
export function namedExports(source) {
  const names = new Set()
  const declaration =
    /^\s*export\s+(?:declare\s+)?(?:abstract\s+)?(?:async\s+)?(?:const\s+enum|const|let|var|function\s*\*?|class|interface|type|enum|namespace|module)\s+([A-Za-z_$][\w$]*)/gm
  for (const match of source.matchAll(declaration)) names.add(match[1])
  for (const match of source.matchAll(/^\s*export\s+(?:type\s+)?\{([^}]*)\}/gm)) {
    for (const spec of match[1].split(',')) {
      const parts = spec
        .trim()
        .replace(/^type\s+/, '')
        .split(/\s+as\s+/)
      const name = parts[parts.length - 1].trim()
      if (name && name !== 'default') names.add(name)
    }
  }
  for (const match of source.matchAll(/^\s*export\s+\*\s+as\s+([A-Za-z_$][\w$]*)/gm)) {
    names.add(match[1])
  }
  return names
}

function defaultName(modulePath) {
  const parts = modulePath.split('/')
  const file = stripExtension(parts[parts.length - 1])
  return pascalCase(file === 'index' && parts.length > 1 ? parts[parts.length - 2] : file)
}

/** The barrel's source text for a folder. */
export function renderBarrel(barrelDir, options = {}) {
  const lines = []
  const owners = new Map()

  const claim = (name, modulePath) => {
    const owner = owners.get(name)
    if (owner && owner !== modulePath) {
      throw new Error(
        `${join(barrelDir, BARREL_FILE)}: "${name}" is exported by both ./${owner} and ` +
          `./${modulePath}. Rename one of them; the barrel can export only one.`,
      )
    }
    owners.set(name, modulePath)
  }

  for (const modulePath of collectModules(barrelDir, options)) {
    const source = readFileSync(join(barrelDir, modulePath), 'utf8')
    const specifier = `./${modulePath}`
    if (hasDefault(source)) {
      const name = defaultName(modulePath)
      claim(name, modulePath)
      lines.push(`export { default as ${name} } from '${specifier}'`)
    }
    if (hasNamed(source)) {
      for (const name of namedExports(source)) claim(name, modulePath)
      lines.push(`export * from '${specifier}'`)
    }
  }

  if (lines.length === 0) lines.push('export {}')
  return [...HEADER, '', ...lines, ''].join('\n')
}

/** The barrel folders a package asks for, as absolute paths. */
export function barrelDirs(packageDir) {
  const manifest = join(packageDir, 'package.json')
  if (!existsSync(manifest)) return []
  const pkg = JSON.parse(readFileSync(manifest, 'utf8'))
  return (pkg.joinery?.barrels ?? []).map(dir => resolve(packageDir, dir))
}

/** Writes every barrel a package asks for; returns the files whose contents changed. */
export function writeBarrels(packageDir) {
  const dirs = barrelDirs(packageDir)
  const changed = []
  for (const dir of dirs) {
    mkdirSync(dir, { recursive: true })
    const source = renderBarrel(dir, { otherBarrels: dirs.filter(other => other !== dir) })
    const file = join(dir, BARREL_FILE)
    // Leave an unchanged barrel alone, so watchers don't rebuild for nothing.
    if (existsSync(file) && readFileSync(file, 'utf8') === source) continue
    writeFileSync(file, source)
    changed.push(file)
  }
  return changed
}

function main(args) {
  const packagesDir = join(repoRoot, 'packages')
  const targets = args.length
    ? args.map(arg => resolve(arg))
    : existsSync(packagesDir)
      ? readdirSync(packagesDir).map(name => join(packagesDir, name))
      : []
  for (const target of targets) {
    for (const file of writeBarrels(target)) {
      console.log(`gen-barrels: wrote ${relative(process.cwd(), file) || basename(file)}`)
    }
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    main(process.argv.slice(2))
  } catch (error) {
    console.error(error.message)
    process.exitCode = 1
  }
}
