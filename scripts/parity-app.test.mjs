// The parity reference app's Vite plugin (parity/upstream-plugin.mjs): the parts that don't need
// the app's own dependencies installed.
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import {
  SHIMS,
  examplesModule,
  exampleEntries,
  generatedDir,
  hasRtlCopy,
  parityRoot,
  rewriteImports,
  selectEntries,
  stylesImported,
  stylesInUse,
  upstreamCss,
} from '../parity/upstream-plugin.mjs'

const INVENTORY = {
  examples: {
    'button-demo': {
      page: 'button',
      styleName: 'radix-nova',
      base: 'radix',
      file: 'apps/v4/examples/radix/button-demo.tsx',
    },
    'button-rtl': {
      page: 'button',
      styleName: 'radix-nova',
      base: 'radix',
      file: 'apps/v4/examples/radix/button-rtl.tsx',
      direction: 'rtl',
    },
    'bubble-demo': {
      page: 'bubble',
      styleName: 'radix-rhea',
      base: 'radix',
      file: 'apps/v4/examples/radix/bubble-demo.tsx',
      align: 'start',
    },
    'combobox-basic': {
      page: 'combobox',
      styleName: 'base-nova',
      base: 'base',
      file: 'apps/v4/examples/base/combobox-basic.tsx',
    },
  },
  charts: [
    {
      name: 'chart-area-default',
      file: 'apps/v4/registry/new-york-v4/charts/chart-area-default.tsx',
      styleName: 'new-york-v4',
    },
  ],
  blocks: [
    {
      name: 'login-01',
      file: 'apps/v4/registry/bases/radix/blocks/login-01/page.tsx',
      styleName: 'radix-nova',
    },
    { name: 'broken', file: null, styleName: 'radix-nova' },
  ],
}

test('exampleEntries covers docs examples, charts and blocks with their layout', () => {
  const entries = exampleEntries(INVENTORY)
  assert.deepEqual(
    entries.map(entry => [entry.id, entry.kind, entry.styleName, entry.direction, entry.align]),
    [
      ['button-demo', 'example', 'radix-nova', 'ltr', 'center'],
      ['button-rtl', 'example', 'radix-nova', 'rtl', 'center'],
      ['bubble-demo', 'example', 'radix-rhea', 'ltr', 'start'],
      ['combobox-basic', 'example', 'base-nova', 'ltr', 'center'],
      ['chart-area-default', 'chart', 'new-york-v4', 'ltr', 'start'],
      ['login-01', 'block', 'radix-nova', 'ltr', 'start'],
    ],
  )
  assert.deepEqual(stylesInUse(entries), ['base-nova', 'radix-nova', 'radix-rhea'])
})

test('selectEntries limits a build to PARITY_EXAMPLES', () => {
  const entries = exampleEntries(INVENTORY)
  assert.equal(selectEntries(entries, undefined), entries)
  assert.deepEqual(
    selectEntries(entries, 'button-demo, login-01').map(entry => entry.id),
    ['button-demo', 'login-01'],
  )
  assert.throws(() => selectEntries(entries, 'nope'), /no upstream example named nope/)
})

test('examplesModule exports a loader per example through the @/ alias', () => {
  const source = examplesModule(selectEntries(exampleEntries(INVENTORY), 'button-rtl'))
  assert.match(source, /^export const examples = \{\n/)
  assert.match(
    source,
    /"button-rtl": \{ \.\.\.\{"id":"button-rtl","kind":"example","styleName":"radix-nova","base":"radix","page":"button","direction":"rtl","align":"center"\}, load: \(\) => import\("@\/examples\/radix\/button-rtl\.tsx"\) \},/,
  )
})

test('rewriteImports points a base ui file at its style, as upstream does', () => {
  const source = [
    'import { Button } from "@/registry/bases/radix/ui/button"',
    'import { useIsMobile } from "@/registry/bases/radix/hooks/use-mobile"',
    'import { cn } from "@/registry/bases/radix/lib/utils"',
    'import { x } from "@/registry/bases/radix/lib/other"',
  ].join('\n')
  assert.equal(
    rewriteImports(source, { base: 'radix', styleName: 'radix-nova' }),
    [
      'import { Button } from "@/styles/radix-nova/ui/button"',
      'import { useIsMobile } from "@/hooks/use-mobile"',
      'import { cn } from "@/lib/utils"',
      'import { x } from "@/lib/other"',
    ].join('\n'),
  )
  assert.ok(hasRtlCopy('radix-nova'))
  assert.ok(hasRtlCopy('base-nova'))
  assert.ok(!hasRtlCopy('radix-rhea'))
})

test('upstreamCss keeps globals.css but points its sources at this app', () => {
  const globals = [
    '@import "tailwindcss";',
    '@import "./legacy-themes.css";',
    '@source "../node_modules/streamdown/dist/*.js";',
    '@source "../styles/radix-nova/**/*.tsx";',
    ':root { --radius: 0.625rem; }',
  ].join('\n')
  const css = upstreamCss(globals, { pageCss: '.parity-stage {}' })
  assert.match(css, /^\/\* Generated by parity\/upstream-plugin\.mjs/)
  assert.match(css, /@import "tailwindcss";/)
  assert.doesNotMatch(css, /legacy-themes/)
  assert.ok(css.includes(`@source "${parityRoot}/node_modules/streamdown/dist/*.js";`))
  assert.ok(css.includes(`@source "${generatedDir}/styles/radix-nova/**/*.tsx";`))
  assert.match(css, /@source ".*\.upstream\/shadcn-ui\/apps\/v4\/examples";/)
  assert.match(css, /\.parity-stage \{\}\n?$/)
})

test('the Next.js stand-ins exist', async () => {
  const { existsSync } = await import('node:fs')
  for (const [module, file] of Object.entries(SHIMS)) assert.ok(existsSync(file), module)
})

test('stylesImported finds every style the upstream sources import', () => {
  const root = mkdtempSync(join(tmpdir(), 'parity-app-'))
  try {
    mkdirSync(join(root, 'components/deep'), { recursive: true })
    writeFileSync(
      join(root, 'components/deep/markdown.tsx'),
      'import { A } from "@/styles/base-rhea/ui/code-block"',
    )
    writeFileSync(join(root, 'components/notes.md'), 'see "@/styles/radix-lyra/ui/button"')
    writeFileSync(join(root, 'components/x.ts'), 'import "@/styles/radix-nova/ui-rtl/button"')
    assert.deepEqual(
      stylesImported([join(root, 'components'), join(root, 'missing')], exampleEntries(INVENTORY)),
      ['base-nova', 'base-rhea', 'radix-nova', 'radix-rhea'],
    )
  } finally {
    rmSync(root, { recursive: true, force: true })
  }
})
